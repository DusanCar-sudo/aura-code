const DICTS: Record<Locale, Dict> = { en, sr, fr, it, es, ar, ru };

/**
 * Look up a key. Falls back to English, then to the key itself — a missing
 * translation should degrade to readable English, never to a blank UI.
 */
export function translate(locale: Locale, key: string): string {
  return DICTS[locale]?.[key] ?? en[key] ?? key;
}

export function detectLocale(): Locale {
  const stored = safeGet('aura.locale');
  if (stored && stored in LOCALES) return stored as Locale;
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return (nav in LOCALES ? nav : 'en') as Locale;
}

/** localStorage can throw outright in private modes; never let that blank the app. */
export function safeGet(key: string): string | null {
  try { return localStorage.getItem(key); } catch { return null; }
}
export function safeSet(key: string, value: string): void {
  try { localStorage.setItem(key, value); } catch { /* not worth failing over */ }
}
